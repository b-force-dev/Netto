// Build a dated local fallback and an idempotent, non-overwriting SQL schedule.
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const context = { window:{} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'data/netto_frontend_puzzles.js'), 'utf8'), context);
const data = context.window.NETTO_REBUILT_PUZZLES;
const dates = ['2026-11-01', '2026-11-02', '2026-11-03'];
const rows = data.daily.slice(2, 5).map((original, index) => {
  const digest = crypto.createHash('sha256').update('netto-daily-' + dates[index]).digest('hex');
  const id = `${digest.slice(0,8)}-${digest.slice(8,12)}-4${digest.slice(13,16)}-a${digest.slice(17,20)}-${digest.slice(20,32)}`;
  assert.ok(original.photo?.url && original.photo?.maker && original.photo?.licentie);
  const [a,b,c] = [original.q1_answer, original.q2_answer, original.q3_answer];
  assert.equal(original.operator === '÷' ? a / b : original.operator === '−' ? a - b : a * b, c);
  return { ...original, id, date:dates[index], number:42 + index, name:`Daily #${42 + index}`,
    image_path:original.photo.url,
    image_alt:original['q' + original.photo.vraag + '_label'],
    image_caption:'With question ' + original.photo.vraag,
    image_credit:original.photo.maker + ' · ' + original.photo.licentie,
    image_source_url:original.photo.pagina };
});
const extension = '// Dailies scheduled for 1–3 November 2026; generated by tools/plan_november_dailies.cjs.\n' +
  '(() => { const data = window.NETTO_REBUILT_PUZZLES; if (!data) return;\n' +
  'const additions = ' + JSON.stringify(rows, null, 2) + ';\n' +
  'for (const puzzle of additions) if (!data.daily.some(existing => existing.date === puzzle.date)) data.daily.push(puzzle);\n})();\n';
fs.writeFileSync(path.join(root, 'data/netto_daily_november.js'), extension);
const quote = value => "'" + String(value).replaceAll("'", "''") + "'";
const columns = ['id','scheduled_date','operator','question_1','question_2','question_3','true_answer_1','true_answer_2','true_answer_3','status','daily_edition','image_path','image_alt','image_caption','image_credit','image_source_url'];
const values = rows.map(p => [p.id,p.date,p.operator,p.q1_label,p.q2_label,p.q3_label,p.q1_answer,p.q2_answer,p.q3_answer,'scheduled',data.daily_edition,p.image_path,p.image_alt,p.image_caption,p.image_credit,p.image_source_url]);
const sql = `-- Netto: 1–3 November 2026, London midnight release (existing timezone rules).
-- Run in Supabase SQL Editor. Existing dates and previous plays are preserved.
begin;
insert into public.puzzles (${columns.join(', ')})
select v.* from (values
${values.map(row => '  (' + row.map(v => typeof v === 'number' ? v : quote(v)).join(', ') + ')').join(',\n')}
) as input(${columns.join(', ')})
cross join lateral (select input.id::uuid as id, input.scheduled_date::date as scheduled_date,
${columns.slice(2).map(c => 'input.' + c).join(', ')}) v
where not exists (select 1 from public.puzzles p where p.scheduled_date = v.scheduled_date)
on conflict (id) do nothing;
do $$ begin
  if (select count(*) from public.puzzles where status='scheduled' and daily_edition=${quote(data.daily_edition)}
      and scheduled_date between date '2026-11-01' and date '2026-11-03') <> 3 then
    raise exception 'Daily schedule is incomplete or a date is already occupied by another edition. No changes saved.';
  end if;
end $$;
commit;
select scheduled_date, question_1, question_2, question_3, image_path, image_credit
from public.puzzles where scheduled_date between date '2026-11-01' and date '2026-11-03'
order by scheduled_date;
`;
fs.writeFileSync(path.join(root, 'supabase/plan_dailies_20261101_03.sql'), sql);
console.log('Prepared 3 dated Dailies with photo credits and valid equations.');
